// COMPONENT: Explicit reading-data export
// PURPOSE: Replace one app-owned Markdown section without changing surrounding source.
// FLOW: Current source + local notes -> validated generated section -> export text.

import Foundation

/// Only standalone markers outside code fences define replaceable source.
enum AnnotationExporter
{
    static let start = "<!-- monomark:reading-data:start -->"
    static let end = "<!-- monomark:reading-data:end -->"

    static func render(source: String, notes: ReadingNotes) throws -> String
    {
        let newline = source.contains("\r\n") ? "\r\n" : "\n"
        let owned = try section(in: source)
        let generated = content(notes).joined(separator: newline) + newline
        if let owned
        {
            return source.replacingCharacters(in: owned, with: generated)
        }
        let separator = source.isEmpty ? "" : source.hasSuffix(newline + newline) ? "" :
            source.hasSuffix(newline) ? newline : newline + newline
        return source + separator + generated
    }

    private static func section(in source: String) throws -> Range<String.Index>?
    {
        var markers: [(String, Range<String.Index>)] = []
        var fence: (Character, Int)?
        source.enumerateSubstrings(in: source.startIndex ..< source.endIndex, options: .byLines)
        { line, _, enclosing, _ in
            let text = line ?? ""
            let stripped = text.drop(while: {
                $0 == " "
            })
            let indentation = text.count - stripped.count
            if indentation <= 3, let first = stripped.first, first == "`" || first == "~"
            {
                let count = stripped.prefix(while: {
                    $0 == first
                }).count
                if let active = fence
                {
                    if first == active.0, count >= active.1,
                       stripped.dropFirst(count).trimmingCharacters(in: .whitespaces).isEmpty
                    {
                        fence = nil
                    }
                }
                else if count >= 3
                {
                    fence = (first, count)
                }
                return
            }
            if fence == nil, text == start || text == end
            {
                markers.append((text, enclosing))
            }
        }
        guard fence == nil
        else
        {
            throw AnnotationFailure.invalidMarkers
        }
        if markers.isEmpty
        {
            return nil
        }
        guard markers.count == 2, markers[0].0 == start, markers[1].0 == end
        else
        {
            throw AnnotationFailure.invalidMarkers
        }
        return markers[0].1.lowerBound ..< markers[1].1.upperBound
    }

    private static func content(_ notes: ReadingNotes) -> [String]
    {
        var lines = [
            start,
            "## MonoMark reading notes",
            "",
            "Auto-generated by MonoMark. Each export replaces this section.",
            ""
        ]
        for (index, annotation) in notes.annotations.enumerated()
        {
            lines += ["### Annotation \(index + 1) (\(annotation.color))", ""]
            lines += quote(annotation.anchors.map(\.quote).joined(separator: "\n"))
            if !annotation.comment.isEmpty
            {
                lines += ["", "Comment:", ""] + quote(annotation.comment)
            }
            lines.append("")
        }
        if !notes.text.isEmpty
        {
            lines += ["### Notes", ""] + noteLines(notes) + [""]
        }
        return lines + [end]
    }

    private static func quote(_ text: String) -> [String]
    {
        text.replacingOccurrences(of: "\r\n", with: "\n")
            .components(separatedBy: "\n").map
            {
                "> " + $0
            }
    }

    private static func noteLines(_ notes: ReadingNotes) -> [String]
    {
        if notes.format != "plain"
        {
            return quote(notes.text)
        }
        let longest = notes.text.split(whereSeparator: {
            $0 != "`"
        }).map(\.count).max() ?? 0
        let fence = String(repeating: "`", count: max(3, longest + 1))
        return ["> " + fence + "text"] + quote(notes.text) + ["> " + fence]
    }
}
