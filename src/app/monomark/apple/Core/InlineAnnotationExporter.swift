// COMPONENT: Explicit inline annotation export
// PURPOSE: Insert replaceable reading data at complete-block boundaries without editing source content.
import Foundation

enum InlineAnnotationExporter
{
    static func render(source: String, notes: ReadingNotes) throws -> String
    {
        guard notes.annotations.isEmpty || notes.sourceHash == DocumentStamp.make(source)
        else
        {
            throw AnnotationFailure.sourceChanged
        }
        let clean = try GeneratedReadingSections.clean(source)
        let translated = clean.translating(notes)
        let newline = source.contains("\r\n") ? "\r\n" : source.contains("\r") ? "\r" : "\n"
        var placements = try plan(translated, newline: newline)
        let offsets = InlineSourceOffsets(placements)
        for index in placements.indices
        {
            placements[index].annotation = offsets.applying(to: placements[index].annotation)
        }
        var output = try insert(placements, into: clean.text, newline: newline)
        if !translated.text.isEmpty
        {
            let lines = [
                "## Monoleaf reading notes",
                "",
                "Auto-generated by Monoleaf. Each export replaces this section.",
                "",
                "### Notes",
                ""
            ] + AnnotationExporter.noteLines(translated)
            output += wrapped(lines, id: "notes", join: needsBreak(output), newline: newline)
        }
        return output
    }

    private static func plan(_ notes: ReadingNotes, newline: String) throws -> [InlineAnnotationPlacement]
    {
        try notes.annotations.enumerated().map
        { index, annotation in
            try annotation.validate()
            guard annotation.anchors.allSatisfy({
                      $0.location?.isValid == true
                  }),
                  let end = annotation.anchors.compactMap(\.location?.endLine).max()
            else
            {
                throw AnnotationFailure.unresolvedLocations
            }
            let lines = AnnotationExporter.annotationLines(annotation, index: index, inline: true)
            let added = wrapped(lines, id: annotation.id, join: false, newline: newline)
                .components(separatedBy: newline).count - 1
            return InlineAnnotationPlacement(annotation: annotation, index: index, endLine: end, addedLines: added)
        }.sorted
        {
            $0.endLine == $1.endLine ? $0.index < $1.index : $0.endLine < $1.endLine
        }
    }

    private static func insert(
        _ placements: [InlineAnnotationPlacement],
        into source: String,
        newline: String
    ) throws -> String
    {
        var output = ""
        output.reserveCapacity(source.utf8.count)
        var cursor = source.startIndex
        var line = 0
        var next = 0
        source.enumerateSubstrings(in: source.startIndex ..< source.endIndex, options: .byLines)
        { _, _, range, _ in
            line += 1
            guard next < placements.count, placements[next].endLine == line
            else
            {
                return
            }
            output += source[cursor ..< range.upperBound]
            cursor = range.upperBound
            while next < placements.count, placements[next].endLine == line
            {
                let placement = placements[next]
                let lines = AnnotationExporter.annotationLines(
                    placement.annotation,
                    index: placement.index,
                    inline: true
                )
                output += wrapped(lines, id: placement.annotation.id, join: needsBreak(output), newline: newline)
                next += 1
            }
        }
        guard next == placements.count
        else
        {
            throw AnnotationFailure.unresolvedLocations
        }
        output += source[cursor...]
        return output
    }

    private static func needsBreak(_ text: String) -> Bool
    {
        !text.isEmpty && text.last?.isNewline != true
    }

    private static func wrapped(_ lines: [String], id: String, join: Bool, newline: String) -> String
    {
        (join ? newline : "") + ReadingDataMarker.start(id: id, join: join) + newline + newline +
            lines.joined(separator: newline) + newline + newline + ReadingDataMarker.end(id: id) + newline
    }
}
